"""
Generates scripts/BuildInfo.g.cs so the C# installer reports the release version.

Version source: --version argument, else the latest git tag (v1.2.3 -> 1.2.3), else 0.0.0.
"""
import argparse
import os
import re
import subprocess

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "BuildInfo.g.cs")


def detect_version() -> str:
    try:
        tag = subprocess.run(["git", "describe", "--tags", "--abbrev=0"], capture_output=True,
                             text=True, check=True).stdout.strip()
        return tag.lstrip("vV")
    except Exception:
        return "0.0.0"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", "-v", default="", help="Version (e.g. 1.0.4 or v1.0.4)")
    version = (parser.parse_args().version or detect_version()).lstrip("vV")

    nums = (re.findall(r"\d+", version.split("-")[0]) + ["0"] * 4)[:4]
    numeric = ".".join(nums)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(
            "// Generated by scripts/write_build_info.py - do not edit.\n"
            "using System.Reflection;\n\n"
            f'[assembly: AssemblyVersion("{numeric}")]\n'
            f'[assembly: AssemblyFileVersion("{numeric}")]\n'
            f'[assembly: AssemblyInformationalVersion("{version}")]\n\n'
            "internal static class BuildInfo\n{\n"
            f'    public const string Version = "{version}";\n'
            "}\n"
        )
    print(f"Wrote {OUT} (version {version})")


if __name__ == "__main__":
    main()
